import { IRFunction, IRModule } from './ir';

export interface NativeCodegenResult {
  supported: boolean;
  cSource?: string;
  reason?: string;
}

const UNSUPPORTED_OPS = new Set<string>([]);
const UNSUPPORTED_BUILTINS = new Set([
  'stringify',
  'parse',
  'split',
]);

/**
 * Native C99 Codegen from Nova IR targeting `libnovart` (`novart.h`).
 * Supports primitives, strings, chars, functions, recursion, globals,
 * conditions, loops, structs, arrays, maps, Result<T, E>, methods, and stdlib.
 */
export function generateNativeC(mod: IRModule): NativeCodegenResult {
  for (const fn of mod.functions) {
    for (const b of fn.blocks) {
      for (const inst of b.instructions) {
        if (UNSUPPORTED_OPS.has(inst.op)) {
          return {
            supported: false,
            reason: `Tensor IR instruction '${inst.op}' executes on the Nova VM + Nova AI Engine.`,
          };
        }
        if (inst.op === 'CALL') {
          const base = inst.callee.includes('.') ? inst.callee.split('.').pop()! : inst.callee;
          if (UNSUPPORTED_BUILTINS.has(base)) {
            return {
              supported: false,
              reason: `AI/JSON builtin '${inst.callee}' runs on Nova VM + Nova AI Engine.`,
            };
          }
        }
      }
    }
  }

  const userFns = new Set(mod.functions.map((f) => f.name));
  const globals = new Set<string>();
  for (const fn of mod.functions) {
    for (const b of fn.blocks) {
      for (const inst of b.instructions) {
        if (inst.op === 'STORE_GLOBAL' || inst.op === 'LOAD_GLOBAL') {
          globals.add(inst.name);
        }
      }
    }
  }

  const sanitize = (name: string): string => name.replace(/[^a-zA-Z0-9_]/g, '_');

  const lines: string[] = [
    '/* Generated by Nova Native Codegen (Nova IR -> C99 + libnovart) */',
    '#include "novart.h"',
    '',
  ];

  for (const g of globals) {
    lines.push(`static NVal g_${sanitize(g)};`);
  }
  if (globals.size > 0) lines.push('');

  // Forward declarations
  for (const fn of mod.functions) {
    const params = fn.params.length > 0 ? fn.params.map((p) => `NVal v_${sanitize(p)}`).join(', ') : 'void';
    lines.push(`static NVal nova_fn_${sanitize(fn.name)}(${params});`);
  }
  lines.push('');

  const emitFunction = (fn: IRFunction): void => {
    const params = fn.params.length > 0 ? fn.params.map((p) => `NVal v_${sanitize(p)}`).join(', ') : 'void';
    lines.push(`static NVal nova_fn_${sanitize(fn.name)}(${params}) {`);

    const temps = new Set<string>();
    const slots = new Set<string>();
    for (const b of fn.blocks) {
      for (const inst of b.instructions) {
        if ('dst' in inst && inst.dst) temps.add(inst.dst);
        if (inst.op === 'STORE' || inst.op === 'LOAD') {
          if (!fn.params.includes(inst.slot)) slots.add(inst.slot);
        }
      }
    }

    for (const t of temps) lines.push(`  NVal ${sanitize(t)} = nv_none();`);
    for (const s of slots) lines.push(`  NVal v_${sanitize(s)} = nv_none();`);

    for (const b of fn.blocks) {
      lines.push(`lbl_${sanitize(b.label)}: ;`);
      for (const inst of b.instructions) {
        switch (inst.op) {
          case 'CONST': {
            const d = sanitize(inst.dst);
            if (inst.value.kind === 'Int') lines.push(`  ${d} = nv_int(${Math.trunc(inst.value.value)}LL);`);
            else if (inst.value.kind === 'Float') lines.push(`  ${d} = nv_float(${inst.value.value});`);
            else if (inst.value.kind === 'Bool') lines.push(`  ${d} = nv_bool(${inst.value.value ? 'true' : 'false'});`);
            else if (inst.value.kind === 'String') lines.push(`  ${d} = nv_str(${JSON.stringify(inst.value.value)});`);
            else if (inst.value.kind === 'Char') lines.push(`  ${d} = nv_char(${JSON.stringify(inst.value.value)});`);
            else lines.push(`  ${d} = nv_none();`);
            break;
          }
          case 'LOAD':
            lines.push(`  ${sanitize(inst.dst)} = v_${sanitize(inst.slot)};`);
            break;
          case 'STORE':
            lines.push(`  v_${sanitize(inst.slot)} = ${sanitize(inst.src)};`);
            break;
          case 'LOAD_GLOBAL':
            lines.push(`  ${sanitize(inst.dst)} = g_${sanitize(inst.name)};`);
            break;
          case 'STORE_GLOBAL':
            lines.push(`  g_${sanitize(inst.name)} = ${sanitize(inst.src)};`);
            break;
          case 'ADD':
            lines.push(`  ${sanitize(inst.dst)} = nv_add(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          case 'SUB':
            lines.push(`  ${sanitize(inst.dst)} = nv_sub(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          case 'MUL':
            lines.push(`  ${sanitize(inst.dst)} = nv_mul(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          case 'DIV':
            lines.push(`  ${sanitize(inst.dst)} = nv_div(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          case 'MOD':
            lines.push(`  ${sanitize(inst.dst)} = nv_mod(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          case 'MATMUL':
            lines.push(`  ${sanitize(inst.dst)} = nv_matmul(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          case 'NEG':
            lines.push(`  ${sanitize(inst.dst)} = nv_neg(${sanitize(inst.src)});`);
            break;
          case 'NOT':
            lines.push(`  ${sanitize(inst.dst)} = nv_not(${sanitize(inst.src)});`);
            break;
          case 'AND':
            lines.push(`  ${sanitize(inst.dst)} = nv_bool(nv_truthy(${sanitize(inst.left)}) && nv_truthy(${sanitize(inst.right)}));`);
            break;
          case 'OR':
            lines.push(`  ${sanitize(inst.dst)} = nv_bool(nv_truthy(${sanitize(inst.left)}) || nv_truthy(${sanitize(inst.right)}));`);
            break;
          case 'COMPARE': {
            const cmpFn: Record<string, string> = {
              '==': 'nv_cmp_eq',
              '!=': 'nv_cmp_neq',
              '<': 'nv_cmp_lt',
              '<=': 'nv_cmp_lte',
              '>': 'nv_cmp_gt',
              '>=': 'nv_cmp_gte',
            };
            lines.push(`  ${sanitize(inst.dst)} = ${cmpFn[inst.cmp]}(${sanitize(inst.left)}, ${sanitize(inst.right)});`);
            break;
          }
          case 'CALL': {
            const d = sanitize(inst.dst);
            const cArgs = inst.args.map(sanitize);
            if (userFns.has(inst.callee)) {
              lines.push(`  ${d} = nova_fn_${sanitize(inst.callee)}(${cArgs.join(', ')});`);
            } else if (cArgs.length === 0) {
              lines.push(`  ${d} = nv_call_builtin(${JSON.stringify(inst.callee)}, 0, NULL);`);
            } else {
              lines.push(`  { NVal _args[] = { ${cArgs.join(', ')} }; ${d} = nv_call_builtin(${JSON.stringify(inst.callee)}, ${cArgs.length}, _args); }`);
            }
            break;
          }
          case 'CALL_METHOD': {
            const d = sanitize(inst.dst);
            const obj = sanitize(inst.object);
            const cArgs = inst.args.map(sanitize);
            if (cArgs.length === 0) {
              lines.push(`  ${d} = nv_method_call(${obj}, ${JSON.stringify(inst.method)}, 0, NULL);`);
            } else {
              lines.push(`  { NVal _args[] = { ${cArgs.join(', ')} }; ${d} = nv_method_call(${obj}, ${JSON.stringify(inst.method)}, ${cArgs.length}, _args); }`);
            }
            break;
          }
          case 'ALLOC_STRUCT': {
            const d = sanitize(inst.dst);
            if (inst.fields.length === 0) {
              lines.push(`  ${d} = nv_alloc_struct(${JSON.stringify(inst.typeName)}, 0, NULL, NULL);`);
            } else {
              const names = inst.fields.map((f) => JSON.stringify(f.name)).join(', ');
              const vals = inst.fields.map((f) => sanitize(f.src)).join(', ');
              lines.push(
                `  { const char* _fnames[] = { ${names} }; NVal _fvals[] = { ${vals} }; ${d} = nv_alloc_struct(${JSON.stringify(inst.typeName)}, ${inst.fields.length}, _fnames, _fvals); }`
              );
            }
            break;
          }
          case 'LOAD_FIELD':
            lines.push(`  ${sanitize(inst.dst)} = nv_load_field(${sanitize(inst.object)}, ${JSON.stringify(inst.field)});`);
            break;
          case 'STORE_FIELD':
            lines.push(`  nv_store_field(${sanitize(inst.object)}, ${JSON.stringify(inst.field)}, ${sanitize(inst.src)});`);
            break;
          case 'ALLOC_ARRAY': {
            const d = sanitize(inst.dst);
            if (inst.elements.length === 0) {
              lines.push(`  ${d} = nv_alloc_array(0, NULL);`);
            } else {
              const els = inst.elements.map(sanitize).join(', ');
              lines.push(`  { NVal _els[] = { ${els} }; ${d} = nv_alloc_array(${inst.elements.length}, _els); }`);
            }
            break;
          }
          case 'ALLOC_MAP': {
            const d = sanitize(inst.dst);
            if (inst.entries.length === 0) {
              lines.push(`  ${d} = nv_alloc_map(0, NULL, NULL);`);
            } else {
              const keys = inst.entries.map((e) => sanitize(e.key)).join(', ');
              const vals = inst.entries.map((e) => sanitize(e.value)).join(', ');
              lines.push(`  { NVal _mk[] = { ${keys} }; NVal _mv[] = { ${vals} }; ${d} = nv_alloc_map(${inst.entries.length}, _mk, _mv); }`);
            }
            break;
          }
          case 'INDEX_GET':
            lines.push(`  ${sanitize(inst.dst)} = nv_index_get(${sanitize(inst.object)}, ${sanitize(inst.index)});`);
            break;
          case 'INDEX_SET':
            lines.push(`  nv_index_set(${sanitize(inst.object)}, ${sanitize(inst.index)}, ${sanitize(inst.src)});`);
            break;
          case 'MAKE_RESULT':
            lines.push(
              `  ${sanitize(inst.dst)} = ${inst.variant === 'Ok' ? 'nv_make_ok' : 'nv_make_error'}(${sanitize(inst.src)});`
            );
            break;
          case 'JUMP':
            lines.push(`  goto lbl_${sanitize(inst.target)};`);
            break;
          case 'JUMP_IF_FALSE':
            lines.push(`  if (!nv_truthy(${sanitize(inst.cond)})) goto lbl_${sanitize(inst.target)};`);
            break;
          case 'RETURN':
            lines.push(`  return ${inst.src ? sanitize(inst.src) : 'nv_none()'};`);
            break;
        }
      }
    }
    lines.push('  return nv_none();');
    lines.push('}');
    lines.push('');
  };

  for (const fn of mod.functions) {
    emitFunction(fn);
  }

  lines.push('int main(void) {');
  if (userFns.has('__init__')) lines.push('  nova_fn___init__();');
  if (userFns.has('main')) lines.push('  nova_fn_main();');
  lines.push('  return 0;');
  lines.push('}');

  return { supported: true, cSource: lines.join('\n') };
}
